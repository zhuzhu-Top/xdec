# Decompile every eval_* function and score against manifest expectations.
#
# Two modes, because two different questions are being asked. Baseline is the
# decompiler on its own: nothing but the binary, which is the situation every
# user starts in and the one no change may regress. Typed adds the imported
# headers and the syscall table -- the same binary, decompiled by a tool that
# was told what a `struct timeval` is. A case declares which modes it is scored
# in, so a case about type import does not count as a baseline failure for
# testing something baseline cannot do.
param(
  [string]$Xdec = (Join-Path (Split-Path $PSScriptRoot -Parent) "build\dev\bin\xdec.exe"),
  [int]$Rounds = 8,
  # Import headers and name syscalls, and score the cases that ask for it.
  [switch]$Typed,
  # Compares against a stored run and fails on any case that used to pass.
  [string]$Baseline,
  # Overwrites the baseline with this run instead of comparing against it.
  [switch]$UpdateBaseline
)

$ErrorActionPreference = "Stop"
$Root = $PSScriptRoot
$Build = Join-Path $Root "build"
$Mode = if ($Typed) { "typed" } else { "baseline" }
$Out = Join-Path $Build "out_$Mode"
$So = Join-Path $Build "libxdec_eval.so"
$Manifest = Join-Path $Root "manifest.json"
$Report = Join-Path $Build "report_$Mode.json"
$CombinedPath = Join-Path $Build "all_$Mode.c"
$Log = Join-Path $Build "run_$Mode.log"
if (-not $Baseline) {
  $Baseline = Join-Path $Root "$(if ($Typed) { 'typed_baseline' } else { 'baseline' }).json"
}

# What the typed mode adds, for every case: the corpus's own header, which is
# deliberately not compiled into the .so (that is the point -- the types have to
# come from outside the binary), and the shipped syscall numbering.
$TypedArgs = @(
  "--types", (Join-Path $Root "corpus\types\eval_types.hdecl"),
  "--syscall-table", "aarch64-linux"
)

if (-not (Test-Path $So)) {
  Write-Host "Building corpus first..."
  & (Join-Path $Root "build.ps1")
}

if (-not (Test-Path $Xdec)) {
  throw "xdec not found: $Xdec`nBuild xdec first (cmake --build build/dev)."
}

New-Item -ItemType Directory -Force -Path $Out | Out-Null
"" | Set-Content $Log

$manifestData = Get-Content $Manifest -Raw | ConvertFrom-Json
$byName = @{}
foreach ($case in $manifestData.cases) { $byName[$case.name] = $case }

$symbols = Get-Content (Join-Path $Build "symbols.txt")
$found = ($symbols | ForEach-Object {
  if ($_ -match '^([0-9a-f]+)\s+\S+\s+(eval_\S+)') {
    # default llvm-nm: 0000000000001c18 T eval_abs
    [PSCustomObject]@{ Va = [Convert]::ToUInt64($matches[1], 16); Name = $matches[2] }
  } elseif ($_ -match '^(eval_\S+)\s+\S+\s+([0-9a-f]+)') {
    # posix: eval_abs T 1c18 c
    [PSCustomObject]@{ Va = [Convert]::ToUInt64($matches[2], 16); Name = $matches[1] }
  }
}) | Sort-Object Name

# A symbol is decompiled when a case asks for it in this mode. Helper functions
# the corpus needs but does not score (a thunk a case calls, say) have no case
# and are skipped: they are reached through their caller, which is the case.
$cases = @()
$skipped = @()
foreach ($symbol in $found) {
  $case = $byName[$symbol.Name]
  if (-not $case) { continue }
  if ($case.PSObject.Properties['enabled'] -and -not $case.enabled) {
    $skipped += "$($symbol.Name) (disabled)"
    continue
  }
  $modes = if ($case.PSObject.Properties['modes']) { @($case.modes) } else { @("baseline", "typed") }
  if ($modes -notcontains $Mode) {
    $skipped += "$($symbol.Name) (not scored in $Mode)"
    continue
  }
  $extra = if ($case.PSObject.Properties['decompile_args']) { @($case.decompile_args) } else { @() }
  $cases += [PSCustomObject]@{ Va = $symbol.Va; Name = $symbol.Name; Extra = $extra }
}

Write-Host "Mode: $Mode"
Write-Host "Decompiling $($cases.Count) function(s) with $Xdec ..."
$errors = @()
$chunks = @(
  "/* xdec eval corpus ($Mode) - generated by eval/run.ps1 */",
  "#include <stdint.h>",
  ""
)

foreach ($case in $cases) {
  $outFile = Join-Path $Out ("{0}.c" -f $case.Name)
  $addr = "0x{0:x}" -f $case.Va
  # Per-case arguments come last so a case can override what the mode set.
  $cliArgs = @($So, $case.Va, "--out", $outFile, "--rounds", $Rounds)
  if ($Typed) { $cliArgs += $TypedArgs }
  $cliArgs += $case.Extra
  Write-Host "  $($case.Name) @ $addr"
  $sw = [Diagnostics.Stopwatch]::StartNew()
  $output = & $Xdec decompile @cliArgs 2>&1
  $sw.Stop()
  Add-Content $Log "$($case.Name) $addr exit=$LASTEXITCODE time=$([int]$sw.Elapsed.TotalSeconds)s args=$($case.Extra -join ' ')"
  if ($LASTEXITCODE -ne 0) {
    $errors += "$($case.Name): decompile failed"
    Add-Content $Log ($output -join "`n")
    continue
  }
  if (-not (Test-Path $outFile)) {
    $errors += "$($case.Name): no output file"
    continue
  }
  $chunks += "// ========== $($case.Name) @ $addr =========="
  $chunks += (Get-Content $outFile -Raw)
  $chunks += ""
}

$chunks -join "`n" | Set-Content -Encoding utf8 $CombinedPath

if ($skipped.Count -gt 0) {
  Write-Host ""
  Write-Host "Skipped $($skipped.Count):"
  $skipped | ForEach-Object { Write-Host "  $_" }
}

Write-Host ""
Write-Host "Scoring..."
$scoreArgs = @((Join-Path $Root "score.py"), $Manifest, $CombinedPath, $Report, "--mode", $Mode)
if ($UpdateBaseline) {
  python @scoreArgs
  $scoreExit = $LASTEXITCODE
  Copy-Item $Report $Baseline -Force
  Write-Host "Baseline updated: $Baseline"
} else {
  python @scoreArgs --baseline $Baseline
  $scoreExit = $LASTEXITCODE
}

Write-Host ""
Write-Host "Per-function outputs: $Out"
Write-Host "Combined: $CombinedPath"
Write-Host "Log: $Log"

if ($errors.Count -gt 0) {
  Write-Host ""
  Write-Host "Decompile errors:"
  $errors | ForEach-Object { Write-Host "  $_" }
}

exit $scoreExit
